"""Generate the website's offline English catalog (no app or training dependencies)."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def sync(check=False):
    catalog = ROOT / 'website/i18n/en.json'
    target = ROOT / 'website/assets/i18n-en.js'
    dictionary = json.loads(catalog.read_text(encoding='utf-8'))
    content = ('// Generated by scripts/sync_site_i18n.py; edit website/i18n/en.json.\n'
               'window.EmoMosaicEnglish = ' + json.dumps(dictionary, ensure_ascii=False, indent=2) + ';\n')
    if check:
        assert target.read_text(encoding='utf-8') == content, 'Run python3 scripts/build_pages.py to refresh translations'
    else:
        target.write_text(content, encoding='utf-8')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    sync(parser.parse_args().check)
